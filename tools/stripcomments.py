"""Remove the C and C++ comments that commentlint.py does not allow.

    uv run tools/stripcomments.py [PATH ...]    # default: every tracked C/C++ file
    uv run tools/stripcomments.py --check       # exit 1 if any file would change

The comments to remove are the ones commentlint.classify_c calls "bad", so
this script and the lint cannot disagree. Strings, character literals and
preprocessor lines are untouched. A line that held only a removed comment is
deleted, a trailing comment is cut with the blanks before it, and the blank
lines left around a removal collapse to at most one (none at the start or end
of a file or block). Line endings and the trailing newline are kept. Running it
twice changes nothing. Generated files are skipped, except the ones in
STRIP_GENERATED, whose "Generated by" header is a comment to remove.
Standard library only.
"""

import argparse
import subprocess
import sys
from pathlib import Path

import commentlint

STRIP_GENERATED = {"include/ta_protos.h", "link/data.cpp", "link/globals.h"}

MARK = ""


def removed_spans(path, text):
    """Character spans of the comments commentlint rejects."""
    spans = []
    for c, status, _ in commentlint.classify_c(path, text):
        if status == "bad":
            end = c.stop
            if text[end - 1:end] == "\r":
                end -= 1
            spans.append((c.begin, end))
    return spans


def join_around(before, after):
    """The text either side of a removed comment, joined without gluing tokens."""
    if not before.strip():
        return before + after.lstrip(" \t")
    if not after.strip():
        return before.rstrip(" \t") + after
    gap = before[-1:].isspace() or after[:1].isspace() or (
        (before[-1:].isalnum() or before[-1:] == "_") and (after[:1].isalnum() or after[:1] == "_"))
    return before.rstrip(" \t") + (" " if gap else "") + after.lstrip(" \t")


def strip_text(path, text):
    """The text with the disallowed comments removed."""
    spans = removed_spans(path, text)
    if not spans:
        return text
    out, pos = [], 0
    for b, e in spans:
        out.append(text[pos:b])
        out.append(MARK)
        pos = e
    out.append(text[pos:])
    parts = "".join(out).split("\n")
    final_newline = parts[-1] == ""
    if final_newline:
        parts.pop()

    items = []
    for part in parts:
        if MARK not in part:
            items.append(part)
            continue
        pieces = part.split(MARK)
        line = pieces[0]
        for piece in pieces[1:]:
            line = join_around(line, piece)
        cr = "\r" if part.endswith("\r") else ""
        items.append(None if not line.strip() else line.rstrip(" \t\r") + cr)

    result = []
    i = 0
    while i < len(items):
        if items[i] is not None and items[i].strip():
            result.append(items[i])
            i += 1
            continue
        j = i
        while j < len(items) and (items[j] is None or not items[j].strip()):
            j += 1
        region = items[i:j]
        blanks = [x for x in region if x is not None]
        if None not in region:
            result.extend(blanks)
        else:
            before = result[-1].rstrip() if result else None
            after = items[j].strip() if j < len(items) else None
            if before is not None and after is not None and not before.endswith("{") \
                    and not after.startswith("}") and blanks:
                result.append(blanks[0])
        i = j
    return "\n".join(result) + ("\n" if final_newline and result else "")


def skipped(path, text):
    return commentlint.is_generated(path, text) and path not in STRIP_GENERATED


def process(root, path, write):
    """True when the file changes."""
    file = Path(root) / path
    old = file.read_bytes().decode("utf-8", errors="surrogateescape")
    if skipped(path, old):
        return False
    new = strip_text(path, old)
    if new == old:
        return False
    if write:
        file.write_bytes(new.encode("utf-8", errors="surrogateescape"))
    return True


def tracked(root):
    names = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True,
                           check=True).stdout.splitlines()
    return [n for n in names if Path(n).suffix in commentlint.C_SUFFIXES]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("paths", nargs="*", help="files to strip (default: tracked C/C++ files)")
    ap.add_argument("--check", action="store_true", help="exit 1 if any file would change")
    args = ap.parse_args(argv)
    root = commentlint.git(".", "rev-parse", "--show-toplevel").strip()
    paths = args.paths or tracked(root)
    changed = [p for p in paths if process(root, p, write=not args.check)]
    for p in changed:
        print(("would change " if args.check else "changed ") + p)
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
