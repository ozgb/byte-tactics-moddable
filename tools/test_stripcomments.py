"""Tests for stripcomments.py.

    uv run tools/test_stripcomments.py
"""

import tempfile
import unittest
from pathlib import Path

import commentlint
import stripcomments


def strip(text, path="src/a.cpp"):
    return stripcomments.strip_text(path, text)


class StripCommentsTest(unittest.TestCase):
    def test_whole_line_comment(self):
        self.assertEqual(strip("int a;\n// note\nint b;\n"), "int a;\nint b;\n")

    def test_trailing_comment(self):
        self.assertEqual(strip("int a;   // note\nint b; /* x */\n"), "int a;\nint b;\n")

    def test_block_comment_spanning_lines(self):
        self.assertEqual(strip("int a;\n/* one\n   two\n*/\nint b;\n"), "int a;\nint b;\n")
        self.assertEqual(strip("a(); /* x\ny */ b();\n"), "a(); b();\n")

    def test_comment_inside_expression(self):
        self.assertEqual(strip("int/**/x = 1 /* c */ + 2;\n"), "int x = 1 + 2;\n")

    def test_slashes_in_strings_kept(self):
        text = 'const char *s = "a // b /* c */"; char c = \'"\';\n#define U "http://x" // go\n'
        self.assertEqual(strip(text), text.replace(" // go", ""))

    def test_kept_todo(self):
        text = "// TODO(#12): finish\nint h; // TODO(#12): finish\n"
        self.assertEqual(strip(text), text)

    def test_kept_markers(self):
        text = ("// FUNCTION: 0x4b6c30\nint f();\n// FUNCTION: 0x4b6c30 _Name\n"
                "// GLOBAL: 0x4fcca8\nint g;\n// ENTRY: 0x4cbcd5 _Blit\n// FLAGS: /Gi\n")
        self.assertEqual(strip(text), text)

    def test_marker_after_code_removed(self):
        self.assertEqual(strip("int g; // GLOBAL: 0x4fcca8\n"), "int g;\n")

    def test_published_doc_comment_kept(self):
        text = "// One line doc.\nint f();\nint g(); // trailing doc\n"
        self.assertEqual(strip(text, "src/state/block.h"), text)
        self.assertEqual(strip("// two\n// lines\nint f();\n", "src/state/block.h"),
                         "// lines\nint f();\n")
        self.assertEqual(strip(text), "int f();\nint g();\n")

    def test_blank_line_collapse(self):
        self.assertEqual(strip("a;\n\n// x\n\n// y\n\nb;\n"), "a;\n\nb;\n")
        self.assertEqual(strip("a;\n// x\n// y\nb;\n"), "a;\nb;\n")
        self.assertEqual(strip("a;\n\n\n\nb;\n"), "a;\n\n\n\nb;\n")

    def test_no_blank_at_start_of_file_or_block(self):
        self.assertEqual(strip("// head\n\nint a;\n"), "int a;\n")
        self.assertEqual(strip("void f() {\n    // x\n\n    g();\n    // y\n}\n"),
                         "void f() {\n    g();\n}\n")
        self.assertEqual(strip("a;\n// tail\n"), "a;\n")

    def test_crlf_kept(self):
        self.assertEqual(strip("int a; // x\r\n// y\r\n\r\n// z\r\nint b;\r\n"),
                         "int a;\r\n\r\nint b;\r\n")
        self.assertEqual(strip("a;\r\n\r\n// x\r\n\r\nb;\r\n"), "a;\r\n\r\nb;\r\n")

    def test_no_final_newline_kept(self):
        self.assertEqual(strip("int a; // x"), "int a;")
        self.assertEqual(strip("int a;\n"), "int a;\n")

    def test_idempotent_and_lint_clean(self):
        text = ("// head\n\n// FUNCTION: 0x401000\nint f() { // a\n    /* b\n       c */\n"
                "    return '\\'' ; // d\n}\n\n\n// TODO(#3): x\n// bare\nint g;\n")
        once = strip(text)
        self.assertEqual(strip(once), once)
        found, _ = commentlint.check_file("src/a.cpp", once, set(range(1, 99)))
        self.assertEqual(found, [])

    def test_generated_skipped_unless_listed(self):
        text = "// Generated by tools/x.py; do not edit.\n// note\nint a;\n"
        self.assertTrue(stripcomments.skipped("src/x.h", text))
        self.assertFalse(stripcomments.skipped("link/globals.h", text))
        self.assertEqual(strip(text, "link/globals.h"), "int a;\n")

    def test_process_and_check(self):
        with tempfile.TemporaryDirectory() as tmp:
            f = Path(tmp) / "a.cpp"
            f.write_bytes(b"int a; // x\r\n")
            self.assertTrue(stripcomments.process(tmp, "a.cpp", write=False))
            self.assertEqual(f.read_bytes(), b"int a; // x\r\n")
            self.assertTrue(stripcomments.process(tmp, "a.cpp", write=True))
            self.assertEqual(f.read_bytes(), b"int a;\r\n")
            self.assertFalse(stripcomments.process(tmp, "a.cpp", write=True))

    def test_non_utf8_bytes_kept(self):
        with tempfile.TemporaryDirectory() as tmp:
            f = Path(tmp) / "a.cpp"
            f.write_bytes(b"char *s = \"\xff\"; // x\n")
            stripcomments.process(tmp, "a.cpp", write=True)
            self.assertEqual(f.read_bytes(), b"char *s = \"\xff\";\n")


if __name__ == "__main__":
    unittest.main()
